"""Gzip web/index.html into src/web_index.h so the UI ships inside the firmware."""
import gzip
import os

try:
    Import("env")  # noqa: F821 - provided by PlatformIO
    root = env.subst("$PROJECT_DIR")  # noqa: F821
except NameError:
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

src = os.path.join(root, "web", "index.html")
dst = os.path.join(root, "src", "web_index.h")

with open(src, "rb") as f:
    data = gzip.compress(f.read(), compresslevel=9, mtime=0)

lines = []
for i in range(0, len(data), 20):
    lines.append("  " + ", ".join(f"0x{b:02x}" for b in data[i:i + 20]) + ",")

header = (
    "// Generated by scripts/embed_web.py from web/index.html - do not edit.\n"
    "#pragma once\n"
    "#include <stdint.h>\n"
    "#include <stddef.h>\n\n"
    f"static const size_t WEB_INDEX_GZ_LEN = {len(data)};\n"
    "static const uint8_t WEB_INDEX_GZ[] = {\n" + "\n".join(lines) + "\n};\n"
)

old = None
if os.path.exists(dst):
    with open(dst, "r") as f:
        old = f.read()
if old != header:
    with open(dst, "w") as f:
        f.write(header)
    print(f"embed_web: wrote {dst} ({len(data)} bytes gzipped)")
